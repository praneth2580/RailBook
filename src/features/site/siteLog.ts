import type { ElementSelector } from './elementSelector'

/** An element clicked or typed in on the companion page, as the page described it. Values of fields aren't kept. */
export interface RecordedElement {
  tag: string
  id?: string
  classes: string[]
  /** Its visible text, for elements that aren't form fields. */
  text?: string
  /** The attributes that help find it: name, type, placeholder, aria-label, title, role, href and for. */
  attributes: Record<string, string>
  /** A CSS path to it, from the nearest ancestor with a usable id, or from body. */
  css: string
}

/**
 * One click or key press on the companion page, or the page moving to a new address. Only under npm run dev: the
 * launcher keeps the last few hundred while it runs, and SitePage shows them.
 */
export interface SiteLogEntry {
  id: number
  /** When it happened, in milliseconds since 1970. */
  at: number
  /** RailBook's own actions, or the person in the companion window. */
  by: 'helper' | 'you'
  kind: 'click' | 'press' | 'page'
  url: string
  /** For a press, the key with its modifiers, such as 'a', 'Enter' or 'Control+a'. In a password field, '•'. */
  key?: string
  element?: RecordedElement
}

// Generated by frameworks rather than written by people, so they change between builds.
const GENERATED = /\d{3,}|^ng-|^mat-|^css-|^jsx-|^sc-|__/

/** Attributes worth finding an element by, best first. */
const FINDING_ATTRIBUTES = ['aria-label', 'placeholder', 'name', 'title']

/** A first try at describing the element for selectors.ts, from the parts least likely to change. */
export function suggestSelector(element: RecordedElement): ElementSelector {
  const { tag } = element
  if (element.id && !GENERATED.test(element.id)) return { tag, id: element.id }
  if (element.text && element.text.length <= 40) return { tag, text: element.text }
  for (const name of FINDING_ATTRIBUTES) {
    const value = element.attributes[name]
    if (value) return { tag, attributes: { [name]: value } }
  }
  const classes = element.classes.filter((name) => !GENERATED.test(name)).slice(0, 2)
  if (classes.length > 0) return { tag, classes }
  return { css: element.css }
}

function literal(value: unknown): string {
  if (typeof value === 'string') return `'${value.replace(/[\\']/g, '\\$&')}'`
  if (Array.isArray(value)) return `[${value.map(literal).join(', ')}]`
  if (typeof value === 'object' && value !== null) {
    const entries = Object.entries(value).map(([key, item]) => {
      const name = /^[A-Za-z_$][\w$]*$/.test(key) ? key : literal(key)
      return `${name}: ${literal(item)}`
    })
    return `{ ${entries.join(', ')} }`
  }
  return String(value)
}

/** The selector as it would be written in selectors.ts. */
export function formatSelector(selector: ElementSelector) {
  return literal(selector)
}

/** A short name for the element, such as button.primary "Search" or input[placeholder="From*"]. */
export function describeElement(element: RecordedElement) {
  const id = element.id ? `#${element.id}` : ''
  const classes = element.classes.slice(0, 2).map((name) => `.${name}`).join('')
  const attribute = FINDING_ATTRIBUTES.find((name) => element.attributes[name])
  const detail = element.text
    ? ` "${element.text.length > 40 ? `${element.text.slice(0, 40)}…` : element.text}"`
    : attribute
      ? `[${attribute}="${element.attributes[attribute]}"]`
      : ''
  return `${element.tag}${id}${classes}${detail}`
}
